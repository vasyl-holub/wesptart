/**
 * `null`, якщо країна не Україна або код невідомий: краще лишити смугу
 * з питанням «Ваша область», ніж підставити навмання.
 */
export function regionByCode(
  country: string | null,
  code: string | null,
): string | null {
  if (!code) return null;
  if (country && country.toUpperCase() !== "UA") return null;

  const clean = code.toUpperCase().replace(/^UA-/, "").padStart(2, "0");
  return BY_CODE[clean] ?? null;
}
